# ============================================================
# 文件名：problem5_weighted_optimization.py
#
# 问题五：加权单目标优化
#123
# 目标函数：
#
#       min J = a * Fs' - (1-a) * Fe'
#
# Fs'：归一化磁芯损耗
# Fe'：归一化传输磁能
#
# 不使用PSO
# 不使用遗传算法
# 不使用P/Q
#
# 直接计算所有可行工况的目标函数J，
# 选择J最小的方案作为最终最优方案。
# ============================================================

import numpy as np
import pandas as pd


# ============================================================
# 1. 参数设置
# ============================================================

FILE_PATH = "附件一（训练集）(1).xlsx"

# ------------------------------------------------------------
# 磁芯损耗权重
#
# a越大：越重视降低磁芯损耗
# a越小：越重视提高传输磁能
#
# 这里暂时取0.8
# ------------------------------------------------------------

a = 0.80


# ============================================================
# 2. 材料工作表
# ============================================================

SHEETS = {

    1: "材料1",

    2: "材料2",

    3: "材料3",

    4: "材料4"
}


# ============================================================
# 3. 存储全部样本
# ============================================================

all_data = []


print("=" * 100)

print("问题五——加权单目标优化")

print("=" * 100)

print(
    f"\n磁芯损耗权重 a = {a:.2f}"
)

print(
    f"传输磁能权重 1-a = {1-a:.2f}"
)


# ============================================================
# 4. 读取附件一
# ============================================================

for material, sheet_name in SHEETS.items():

    print(
        f"\n正在读取：{sheet_name}"
    )

    df = pd.read_excel(
        FILE_PATH,
        sheet_name=sheet_name
    )


    # --------------------------------------------------------
    # 温度
    # --------------------------------------------------------

    temperature = (
        df.iloc[:, 0]
        .to_numpy(dtype=float)
    )


    # --------------------------------------------------------
    # 频率
    # --------------------------------------------------------

    frequency = (
        df.iloc[:, 1]
        .to_numpy(dtype=float)
    )


    # --------------------------------------------------------
    # 磁芯损耗
    #
    # 当前直接使用附件一实测磁芯损耗。
    #
    # 如果之后要严格使用“问题四预测模型”，
    # 只需要把这里替换成问题四模型预测值即可。
    # --------------------------------------------------------

    core_loss = (
        df.iloc[:, 2]
        .to_numpy(dtype=float)
    )


    # --------------------------------------------------------
    # 励磁波形
    # --------------------------------------------------------

    waveform = (
        df.iloc[:, 3]
        .astype(str)
        .to_numpy()
    )


    # --------------------------------------------------------
    # 1024个磁通密度采样点
    # --------------------------------------------------------

    B_matrix = (
        df.iloc[:, 4:1028]
        .to_numpy(dtype=float)
    )


    # --------------------------------------------------------
    # 磁通密度峰值
    #
    # Bm = max |B(t)|
    # --------------------------------------------------------

    Bm = np.max(
        np.abs(B_matrix),
        axis=1
    )


    # --------------------------------------------------------
    # 传输磁能
    #
    # Fe = f * Bm
    # --------------------------------------------------------

    Fe = (
        frequency
        * Bm
    )


    # --------------------------------------------------------
    # 保存
    # --------------------------------------------------------

    for i in range(len(df)):

        all_data.append({

            "材料":
                f"材料{material}",

            "温度":
                temperature[i],

            "频率":
                frequency[i],

            "波形":
                waveform[i],

            "磁通密度峰值":
                Bm[i],

            "磁芯损耗Fs":
                core_loss[i],

            "传输磁能Fe":
                Fe[i]
        })


# ============================================================
# 5. 汇总为DataFrame
# ============================================================

result = pd.DataFrame(
    all_data
)


# ============================================================
# 6. 删除无效数据
# ============================================================

result = (

    result

    .replace(
        [np.inf, -np.inf],
        np.nan
    )

    .dropna()

    .reset_index(drop=True)
)


# ============================================================
# 7. 获取两个目标函数范围
#
# 用于Min-Max归一化
# ============================================================

Fs_min = result[
    "磁芯损耗Fs"
].min()

Fs_max = result[
    "磁芯损耗Fs"
].max()


Fe_min = result[
    "传输磁能Fe"
].min()

Fe_max = result[
    "传输磁能Fe"
].max()


print(
    "\n"
    + "=" * 100
)

print(
    "目标函数归一化范围"
)

print(
    "=" * 100
)

print(
    f"Fs_min = {Fs_min:.6f}"
)

print(
    f"Fs_max = {Fs_max:.6f}"
)

print(
    f"Fe_min = {Fe_min:.6f}"
)

print(
    f"Fe_max = {Fe_max:.6f}"
)


# ============================================================
# 8. 对磁芯损耗进行归一化
#
# Fs越小越好
#
# Fs' =
#
# Fs - Fs_min
# ---------------
# Fs_max-Fs_min
#
# 最小损耗 -> 0
# 最大损耗 -> 1
# ============================================================

result[
    "Fs_norm"
] = (

    (
        result["磁芯损耗Fs"]
        - Fs_min
    )

    /

    (
        Fs_max
        - Fs_min
    )
)


# ============================================================
# 9. 对传输磁能进行归一化
#
# Fe越大越好
#
# Fe' =
#
# Fe - Fe_min
# ---------------
# Fe_max-Fe_min
#
# 最大磁能 -> 1
# ============================================================

result[
    "Fe_norm"
] = (

    (
        result["传输磁能Fe"]
        - Fe_min
    )

    /

    (
        Fe_max
        - Fe_min
    )
)


# ============================================================
# 10. 建立加权单目标函数
#
#       J = a Fs' - (1-a) Fe'
#
# 由于：
#
# Fs越小越好
# Fe越大越好
#
# 因此J越小越好
# ============================================================

result[
    "J"
] = (

    a
    * result[
        "Fs_norm"
    ]

    -

    (
        1 - a
    )

    * result[
        "Fe_norm"
    ]
)


# ============================================================
# 11. 按J从小到大排序
# ============================================================

result = (

    result

    .sort_values(
        by="J",
        ascending=True
    )

    .reset_index(drop=True)
)


# ============================================================
# 12. 添加排名
# ============================================================

result.insert(

    0,

    "排名",

    np.arange(
        1,
        len(result) + 1
    )
)


# ============================================================
# 13. 提取全局最优方案
# ============================================================

best = result.iloc[0]


# ============================================================
# 14. 输出最终结果
# ============================================================

print(
    "\n"
    + "=" * 100
)

print(
    "问题五——加权单目标优化最终结果"
)

print(
    "=" * 100
)


print(
    "\n【权重】"
)

print(
    f"a = {a:.4f}"
)

print(
    f"1-a = {1-a:.4f}"
)


print(
    "\n【最优五变量组合】"
)

print(
    f"最优温度 T = "
    f"{best['温度']:.0f} ℃"
)

print(
    f"最优频率 f = "
    f"{best['频率']:.2f} Hz"
)

print(
    f"最优励磁波形 = "
    f"{best['波形']}"
)

print(
    f"最优磁通密度峰值 Bm = "
    f"{best['磁通密度峰值']:.6f} T"
)

print(
    f"最优磁芯材料 = "
    f"{best['材料']}"
)


print(
    "\n【两个原始目标】"
)

print(
    f"磁芯损耗 Fs = "
    f"{best['磁芯损耗Fs']:.6f}"
)

print(
    f"传输磁能 Fe = "
    f"{best['传输磁能Fe']:.6f}"
)


print(
    "\n【归一化目标】"
)

print(
    f"Fs' = "
    f"{best['Fs_norm']:.10f}"
)

print(
    f"Fe' = "
    f"{best['Fe_norm']:.10f}"
)


print(
    "\n【综合目标函数】"
)

print(
    "J = a·Fs' - (1-a)·Fe'"
)

print(
    f"J = {best['J']:.10f}"
)


# ============================================================
# 15. 输出排名前10的工况
# ============================================================

print(
    "\n"
    + "=" * 100
)

print(
    "综合目标函数J最优的前10种工况"
)

print(
    "=" * 100
)


show_columns = [

    "排名",

    "温度",

    "频率",

    "波形",

    "磁通密度峰值",

    "材料",

    "磁芯损耗Fs",

    "传输磁能Fe",

    "Fs_norm",

    "Fe_norm",

    "J"
]


print(

    result[
        show_columns
    ]

    .head(10)

    .to_string(
        index=False
    )
)


# ============================================================
# 16. 保存结果
# ============================================================

result.to_csv(

    "problem5_weighted_optimization_results.csv",

    index=False,

    encoding="utf-8-sig"
)


print(
    "\n"
    + "=" * 100
)

print(
    "完整优化结果已保存至："
)

print(
    "problem5_weighted_optimization_results.csv"
)

print(
    "=" * 100
)

print(
    "程序运行结束"
)

print(
    "=" * 100
)
